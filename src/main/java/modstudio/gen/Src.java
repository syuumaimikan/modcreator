package modstudio.gen;

import java.util.TreeSet;

/** Java source builder with import management and indentation. */
public final class Src {
    private final String pkg;
    private final TreeSet<String> imports = new TreeSet<>();
    private final StringBuilder body = new StringBuilder();
    private int indent;

    public Src(String pkg) {
        this.pkg = pkg;
    }

    public Src imp(String... classes) {
        for (String c : classes) {
            int dot = c.lastIndexOf('.');
            if (dot > 0 && c.substring(0, dot).equals(pkg)) continue;
            imports.add(c);
        }
        return this;
    }

    public Src l(String line) {
        if (line.startsWith("}")) indent = Math.max(0, indent - 1);
        if (!line.isEmpty()) body.append("    ".repeat(indent));
        body.append(line).append('\n');
        if (line.endsWith("{")) indent++;
        return this;
    }

    public Src blank() {
        body.append('\n');
        return this;
    }

    @Override
    public String toString() {
        StringBuilder sb = new StringBuilder();
        sb.append("// Generated by ModStudio. Changes are overwritten on export; use Code Files for custom code.\n");
        sb.append("package ").append(pkg).append(";\n\n");
        for (String i : imports) sb.append("import ").append(i).append(";\n");
        if (!imports.isEmpty()) sb.append('\n');
        sb.append(body);
        return sb.toString();
    }

    /** Java string literal with escapes; non-ASCII is written as unicode escapes. */
    public static String str(String s) {
        if (s == null) s = "";
        StringBuilder sb = new StringBuilder("\"");
        for (char c : s.toCharArray()) {
            switch (c) {
                case '"' -> sb.append("\\\"");
                case '\\' -> sb.append("\\\\");
                case '\n' -> sb.append("\\n");
                case '\r' -> {
                }
                case '\t' -> sb.append("\\t");
                default -> {
                    if (c < 32 || c > 126) sb.append(String.format("\\u%04x", (int) c));
                    else sb.append(c);
                }
            }
        }
        return sb.append('"').toString();
    }

    public static String f(double d) {
        String s = Double.toString(d);
        return s + "F";
    }

    public static String d(double d) {
        return Double.toString(d) + "D";
    }
}
